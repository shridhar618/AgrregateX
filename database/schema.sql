SET TIME ZONE 'UTC';
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
CREATE TABLE tenants(id int PRIMARY KEY, name text NOT NULL);
CREATE TABLE products(tenant_id int REFERENCES tenants, id int, category_id int NOT NULL, name text NOT NULL, PRIMARY KEY(tenant_id,id), UNIQUE(tenant_id,id,category_id));
CREATE TABLE customers(tenant_id int REFERENCES tenants, id int, PRIMARY KEY(tenant_id,id));
CREATE TABLE orders(
 tenant_id int NOT NULL, id bigint GENERATED BY DEFAULT AS IDENTITY,
 customer_id int NOT NULL, product_id int NOT NULL, category_id int NOT NULL,
 ordered_at timestamptz NOT NULL, status text NOT NULL CHECK(status IN ('placed','shipped','cancelled')),
 quantity int NOT NULL CHECK(quantity BETWEEN 1 AND 100000), unit_price_cents bigint NOT NULL CHECK(unit_price_cents BETWEEN 0 AND 1000000000),
 version int NOT NULL DEFAULT 1,
 PRIMARY KEY(tenant_id,id),
 FOREIGN KEY(tenant_id,customer_id) REFERENCES customers,
 FOREIGN KEY(tenant_id,product_id,category_id) REFERENCES products(tenant_id,id,category_id)
);
CREATE INDEX orders_time ON orders(tenant_id,ordered_at) INCLUDE(product_id,category_id,status,quantity,unit_price_cents);
CREATE TABLE daily_product(tenant_id int NOT NULL, bucket timestamptz NOT NULL,product_id int NOT NULL,category_id int NOT NULL,status text NOT NULL,n bigint NOT NULL,units bigint NOT NULL,cents bigint NOT NULL,PRIMARY KEY(tenant_id,bucket,product_id,category_id,status));
CREATE TABLE hourly_category(tenant_id int NOT NULL,bucket timestamptz NOT NULL,category_id int NOT NULL,status text NOT NULL,n bigint NOT NULL,units bigint NOT NULL,cents bigint NOT NULL,PRIMARY KEY(tenant_id,bucket,category_id,status));
CREATE TABLE events(tenant_id int NOT NULL,event_id text NOT NULL,fingerprint text NOT NULL,result jsonb,PRIMARY KEY(tenant_id,event_id));
CREATE FUNCTION maintain_rollups() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=pg_catalog,public AS $$
DECLARE r record;
BEGIN
 -- Serialize source image differences in a deterministic key order.
 FOR r IN
  SELECT tenant_id,date_trunc('day',ordered_at,'UTC') bucket,product_id,category_id,status,sum(sign)::bigint n,sum(sign*quantity)::bigint units,sum(sign*quantity::bigint*unit_price_cents)::bigint cents
  FROM (SELECT OLD.tenant_id,OLD.ordered_at,OLD.product_id,OLD.category_id,OLD.status,OLD.quantity,OLD.unit_price_cents,-1 sign WHERE TG_OP IN ('UPDATE','DELETE')
        UNION ALL SELECT NEW.tenant_id,NEW.ordered_at,NEW.product_id,NEW.category_id,NEW.status,NEW.quantity,NEW.unit_price_cents,1 WHERE TG_OP IN ('UPDATE','INSERT')) d
  GROUP BY tenant_id,bucket,product_id,category_id,status HAVING sum(sign)<>0 OR sum(sign*quantity)<>0 OR sum(sign*quantity::bigint*unit_price_cents)<>0 ORDER BY tenant_id,bucket,product_id,category_id,status
 LOOP
  INSERT INTO public.daily_product VALUES(r.tenant_id,r.bucket,r.product_id,r.category_id,r.status,r.n,r.units,r.cents)
  ON CONFLICT(tenant_id,bucket,product_id,category_id,status) DO UPDATE SET n=daily_product.n+excluded.n,units=daily_product.units+excluded.units,cents=daily_product.cents+excluded.cents;
 END LOOP;
 FOR r IN
  SELECT tenant_id,date_trunc('hour',ordered_at,'UTC') bucket,category_id,status,sum(sign)::bigint n,sum(sign*quantity)::bigint units,sum(sign*quantity::bigint*unit_price_cents)::bigint cents
  FROM (SELECT OLD.tenant_id,OLD.ordered_at,OLD.category_id,OLD.status,OLD.quantity,OLD.unit_price_cents,-1 sign WHERE TG_OP IN ('UPDATE','DELETE')
        UNION ALL SELECT NEW.tenant_id,NEW.ordered_at,NEW.category_id,NEW.status,NEW.quantity,NEW.unit_price_cents,1 WHERE TG_OP IN ('UPDATE','INSERT')) d
  GROUP BY tenant_id,bucket,category_id,status HAVING sum(sign)<>0 OR sum(sign*quantity)<>0 OR sum(sign*quantity::bigint*unit_price_cents)<>0 ORDER BY tenant_id,bucket,category_id,status
 LOOP
  INSERT INTO public.hourly_category VALUES(r.tenant_id,r.bucket,r.category_id,r.status,r.n,r.units,r.cents)
  ON CONFLICT(tenant_id,bucket,category_id,status) DO UPDATE SET n=hourly_category.n+excluded.n,units=hourly_category.units+excluded.units,cents=hourly_category.cents+excluded.cents;
 END LOOP;
 RETURN NULL;
END $$;
CREATE TRIGGER rollups AFTER INSERT OR UPDATE OR DELETE ON orders FOR EACH ROW EXECUTE FUNCTION maintain_rollups();
REVOKE ALL ON FUNCTION maintain_rollups() FROM PUBLIC;
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['orders','products','customers','daily_product','hourly_category','events'] LOOP
  EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY',t);
  EXECUTE format('CREATE POLICY tenant_context ON %I TO agrregatex_api USING (tenant_id = nullif(current_setting(''app.tenant'',true),'''')::int) WITH CHECK (tenant_id = nullif(current_setting(''app.tenant'',true),'''')::int)',t);
 END LOOP;
END $$;
GRANT SELECT ON orders,products,customers,daily_product,hourly_category TO agrregatex_api;
GRANT INSERT,UPDATE,DELETE ON orders TO agrregatex_api;
GRANT SELECT,INSERT,UPDATE ON events TO agrregatex_api;
GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO agrregatex_api;
ALTER ROLE agrregatex_api SET statement_timeout='3s';
ALTER ROLE agrregatex_api SET idle_in_transaction_session_timeout='10s';
